'use strict';
/**
 * Local test targets for tls-scan. Three servers with deliberately
 * different TLS postures:
 *
 *   9443 "modern"  TLS1.2+1.3, strong PFS ciphers, server cipher order,
 *                  OCSP stapling (dummy response), long HSTS
 *   9444 "legacy"  TLS1.0-1.2, weak ciphers (3DES, RSA key exchange),
 *                  client cipher order, no HSTS, no OCSP
 *   9445 "mixed"   TLS1.1-1.2, mix of strong + non-PFS ciphers,
 *                  client cipher order, short HSTS max-age
 *
 * Every connection that sends data gets a tiny HTTP response so the
 * scanner's HSTS probe has something to read. Failed handshakes (the
 * scanner causes plenty on purpose) are logged, never fatal.
 */
const tls = require('node:tls');
const fs = require('node:fs');
const path = require('node:path');

const CERT_DIR = path.join(__dirname, 'certs');
const selfSigned = {
  key: fs.readFileSync(path.join(CERT_DIR, 'key.pem')),
  cert: fs.readFileSync(path.join(CERT_DIR, 'cert.pem')),
};
const caSigned = {
  key: fs.readFileSync(path.join(CERT_DIR, 'server-key.pem')),
  cert: fs.readFileSync(path.join(CERT_DIR, 'server-cert.pem')),
};
const ocspDer = fs.existsSync(path.join(CERT_DIR, 'ocsp.der'))
  ? fs.readFileSync(path.join(CERT_DIR, 'ocsp.der'))
  : null;

const SERVERS = [
  {
    name: 'modern',
    port: 9443,
    creds: caSigned,
    opts: {
      minVersion: 'TLSv1.2',
      maxVersion: 'TLSv1.3',
      ciphers: 'ECDHE+AESGCM:ECDHE+CHACHA20',
      honorCipherOrder: true,
    },
    // real OCSP response generated by gen-certs.sh
    ocspResponse: ocspDer,
    hsts: 'max-age=63072000; includeSubDomains; preload',
  },
  {
    name: 'legacy',
    port: 9444,
    creds: selfSigned,
    opts: {
      minVersion: 'TLSv1',
      maxVersion: 'TLSv1.2',
      // everything OpenSSL will still do, incl. 3DES and RSA key exchange
      ciphers: 'ALL:COMPLEMENTOFALL:@SECLEVEL=0',
      honorCipherOrder: false,
    },
    hsts: null,
  },
  {
    name: 'mixed',
    port: 9445,
    creds: selfSigned,
    opts: {
      minVersion: 'TLSv1.1',
      maxVersion: 'TLSv1.2',
      ciphers: 'ECDHE+AESGCM:AES128-SHA:AES256-SHA:DES-CBC3-SHA:@SECLEVEL=0',
      honorCipherOrder: false,
    },
    hsts: 'max-age=300',
  },
];

for (const s of SERVERS) {
  const server = tls.createServer({ ...s.creds, ...s.opts });
  if (s.ocspResponse) {
    // Node staples OCSP via the OCSPRequest event, not a static option
    server.on('OCSPRequest', (_cert, _issuer, cb) => cb(null, s.ocspResponse));
  }
  server.on('secureConnection', (sock) => {
    sock.once('data', () => {
      const headers = [
        'HTTP/1.1 200 OK',
        'Content-Type: text/plain',
        'Content-Length: 2',
        'Connection: close',
      ];
      if (s.hsts) headers.splice(2, 0, `Strict-Transport-Security: ${s.hsts}`);
      sock.end(headers.join('\r\n') + '\r\n\r\nok');
    });
    sock.on('error', () => {});
  });
  server.on('tlsClientError', (err) => {
    // expected: the scanner probes unsupported versions/ciphers
    if (process.env.VERBOSE) {
      console.error(`[${s.name}] client error: ${String(err.message || err).split('\n')[0]}`);
    }
  });
  server.listen(s.port, '127.0.0.1', () => {
    console.log(`[${s.name}] listening on 127.0.0.1:${s.port}`);
  });
}

process.on('SIGINT', () => process.exit(0));
process.on('SIGTERM', () => process.exit(0));
